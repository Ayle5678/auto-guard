const CATALOGS: Record<Lang, Record<UiKey, string>> = { zh, en }

/** Translate one chrome string with `{param}` interpolation. */
export function t(lang: Lang, key: UiKey, params: Record<string, string | number> = {}): string {
  let text = CATALOGS[lang][key]
  for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}

/**
 * Four-layer language resolution for the TUI (ADR-0011):
 * `AUTO_GUARD_LANG` > selected root's config.lang > machine default > zh.
 */
export function resolveUiLang(options: { env?: Record<string, string | undefined>; configLang?: Lang; machineLangPath?: string } = {}): Lang {
  return effectiveLang({
    env: envLang(options.env ?? process.env),
    configLang: options.configLang,
    machineLang: readMachineLang(options.machineLangPath ?? machineConfigPath(homedir())),
  })
}
